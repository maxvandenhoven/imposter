import type { CatalogCategory, WordMode } from "@/api/types";
import { Field, FieldDescription, FieldLabel } from "@/components/ui/field";
import { Input } from "@/components/ui/input";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { ANY_CATEGORY, type SetupForm } from "@/lib/setup";

/** Radix selects cannot hold an empty value, so "any category" has its own. */
const ANY_CATEGORY_ITEM = "any";

function CategorySelect({
  categories,
  value,
  onChange,
  anyLabel,
}: {
  categories: CatalogCategory[];
  value: string;
  onChange: (category: string) => void;
  anyLabel: string;
}) {
  const selected = value === ANY_CATEGORY ? ANY_CATEGORY_ITEM : value;
  const description = categories.find((category) => category.name === value)?.description;

  return (
    <Field>
      <FieldLabel htmlFor="category">Category</FieldLabel>
      <Select
        value={selected}
        onValueChange={(item) => {
          onChange(item === ANY_CATEGORY_ITEM ? ANY_CATEGORY : item);
        }}
      >
        <SelectTrigger id="category" className="w-full">
          <SelectValue />
        </SelectTrigger>
        <SelectContent>
          <SelectItem value={ANY_CATEGORY_ITEM}>{anyLabel}</SelectItem>
          {categories.map((category) => (
            <SelectItem key={category.name} value={category.name}>
              {category.name}
            </SelectItem>
          ))}
        </SelectContent>
      </Select>
      {description !== undefined && <FieldDescription>{description}</FieldDescription>}
    </Field>
  );
}

/**
 * How the secret word is chosen: at random from a category (`random`), typed with an
 * optional category of free text (`typed`, shown as Custom), or generated by a model.
 */
export function WordOptions({
  form,
  categories,
  onChange,
}: {
  form: SetupForm;
  categories: CatalogCategory[];
  onChange: (patch: Partial<SetupForm>) => void;
}) {
  const setCategory = (category: string) => {
    onChange({ category });
  };
  const known = new Set(categories.map((category) => category.name));

  return (
    <Tabs
      value={form.wordMode}
      onValueChange={(mode) => {
        // A custom category is not in the list of random categories.
        const category =
          mode === "random" && !known.has(form.category) ? ANY_CATEGORY : form.category;
        onChange({ wordMode: mode as WordMode, category });
      }}
    >
      <TabsList>
        <TabsTrigger value="random">Random</TabsTrigger>
        <TabsTrigger value="typed">Custom</TabsTrigger>
        <TabsTrigger value="generated">Generated</TabsTrigger>
      </TabsList>
      <TabsContent value="random" className="pt-3">
        <CategorySelect
          categories={categories}
          value={form.category}
          onChange={setCategory}
          anyLabel="Any category"
        />
      </TabsContent>
      <TabsContent value="typed" className="flex flex-col gap-4 pt-3">
        <Field>
          <FieldLabel htmlFor="secret-word">Secret word</FieldLabel>
          <Input
            id="secret-word"
            className="w-full"
            autoComplete="off"
            placeholder="lighthouse"
            value={form.word}
            onChange={(event) => {
              onChange({ word: event.target.value });
            }}
          />
          <FieldDescription>
            One word. Pick one that allows many different clues, since a word that one
            clue gives away makes the game short.
          </FieldDescription>
        </Field>
        <Field>
          <FieldLabel htmlFor="custom-category">Category</FieldLabel>
          <Input
            id="custom-category"
            className="w-full"
            autoComplete="off"
            placeholder="buildings"
            value={form.category}
            onChange={(event) => {
              setCategory(
                event.target.value.trim() === "" ? ANY_CATEGORY : event.target.value,
              );
            }}
          />
          <FieldDescription>
            Optional. A short, broad theme the word belongs to, such as emotions, animals
            or buildings. Players only see it with the public category rule, and the
            imposter hint is based on it.
          </FieldDescription>
        </Field>
      </TabsContent>
      <TabsContent value="generated" className="pt-3">
        <p className="text-sm text-muted-foreground">
          Gemini 3.5 Flash-Lite makes up a fresh word and a category for it when the game
          starts, avoiding the words of recent games.
        </p>
      </TabsContent>
    </Tabs>
  );
}
